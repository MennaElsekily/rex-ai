"""
Opt-in end-to-end check with the REAL local model (Ollama), skipped by
default: set REX_REAL_MODEL_TESTS=1 to run it (several minutes).

FakeLLM tests always answer perfectly, so they could not show what the
admin actually saw: a real small model's curriculum was often a draft,
and its bilingual companion was never created. This runs the real
CurriculumAgent on an ordinary request that names no language, then the
real Streamlit page (AppTest) and the real AdminService on the records it
produced -- all on conftest.py's temporary storage, never the project's
databases.
"""

import os
from io import BytesIO

import pytest

from agents.curriculum_research import curriculum_tools
from agents.curriculum_research.academy_courses import AcademyCatalogue
from agents.curriculum_research.curriculum_agent import CurriculumAgent
from agents.curriculum_research.curriculum_store import CurriculumStore
from tests.test_rex_ai_app import _keys, click, env, start, unlock  # noqa: F401  (env is a fixture)

pytestmark = pytest.mark.skipif(os.environ.get("REX_REAL_MODEL_TESTS") != "1",
                                reason="Real-model test: set REX_REAL_MODEL_TESTS=1 (needs Ollama).")


def _cover(path) -> str:
    from pypdf import PdfReader

    return PdfReader(BytesIO(path.read_bytes())).pages[0].extract_text()


def test_real_model_generation_gives_both_languages_reviewable_and_downloadable_in_the_ui(env, tmp_path):
    from agents.curriculum_research.llm import get_llm
    from knowledge_base.vector_store import VectorStore

    store = CurriculumStore()   # conftest: a temporary default path, the same one the admin page opens
    # An empty temporary index: vector_store=None would open the project's index.
    empty_index = VectorStore(persist_directory=tmp_path / "empty_index")
    tools = curriculum_tools.CurriculumToolbox(
        store=store, catalogue=AcademyCatalogue(vector_store=empty_index,
                                                evidence_search=lambda q: {"status": "ok", "chunks": []},
                                                translate=lambda text: text))
    agent = CurriculumAgent(tools=tools, llm=get_llm(os.environ.get("CURRICULUM_LLM_MODEL") or "qwen2.5:3b"))
    response = agent.process_request({"request_id": "e2e", "context": {}, "user_input":
                                      "Create a 40-hour Digital Marketing curriculum for beginners."})
    agent.close()

    result = response["result"]
    en_id, ar_id = result["curriculum_id"], result.get("bilingual_companion_id")
    assert ar_id, result.get("bilingual_companion_error")
    assert store.translation_of(en_id) == ar_id
    records = {cid: store.get(cid) for cid in (en_id, ar_id)}
    assert records[en_id]["content"]["language"] == "en" and records[ar_id]["content"]["language"] == "ar"
    for record in records.values():   # each language validated on its own; the status follows its own result
        assert record["status"] == ("pending_review" if record["validation"]["valid"] else "draft")
    assert store.documents(en_id) == store.documents(ar_id) == []   # no PDF before approval
    print("\nreal-model statuses:", {r["content"]["language"]: r["status"] for r in records.values()},
          "\nEN errors:", [e["message"] for e in records[en_id]["validation"]["errors"]],
          "\nAR errors:", [e["message"] for e in records[ar_id]["validation"]["errors"]])

    env["orchestrator"].handle_request.return_value = {"status": "success", "result": [response]}
    at = click(unlock(start(), section="agents"), "agent_example_0")

    assert {b.key for b in at.download_button} == set()
    for cid, record in records.items():
        approve_key = f"chat_cur_approve_{cid}_v1_0"
        if record["status"] == "pending_review":
            assert approve_key in _keys(at)
        else:
            assert approve_key not in _keys(at)
            assert f"chat_cur_edit_{cid}_v1_0" in _keys(at)
            assert any("fix these validation problems" in w.value for w in at.warning)

    for cid, record in records.items():
        if record["status"] == "pending_review":
            click(at, f"chat_cur_approve_{cid}_v1_0")
            assert store.get(cid)["status"] == "approved"
            assert [d["version"] for d in store.documents(cid)] == [1]   # generated by the approval
            assert f"chat_cur_pdf_{cid}_0_v1" in {b.key for b in at.download_button}
            if record["content"]["language"] == "en":
                latest = store.documents(cid)[-1]
                assert "Approved by the academy" in _cover(curriculum_tools.DEFAULT_DOCUMENTS_DIR / latest["filename"])

    both_approved = all(store.get(cid)["status"] == "approved" for cid in records)
    assert (f"chat_cur_zip_{en_id}_0" in {b.key for b in at.download_button}) == both_approved
